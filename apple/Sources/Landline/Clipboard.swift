import AppKit

/// The pasteboard calls clipboard sync needs, so tests and demo mode can use
/// one that is not the user's.
@MainActor
protocol Pasteboard: AnyObject {
    /// Goes up by one on every change, by any app.
    var changeCount: Int { get }
    /// Type identifiers of the current contents.
    var types: [String] { get }
    func string() -> String?
    /// Replaces the contents. `concealed` adds the marker that tells
    /// clipboard managers not to record it. Returns the new change count.
    @discardableResult func write(_ text: String, concealed: Bool) -> Int
}

/// The markers from nspasteboard.org that password managers and other tools
/// put next to contents that should not be recorded or synced.
enum PasteboardMarker {
    static let concealed = "org.nspasteboard.ConcealedType"
    static let transient = "org.nspasteboard.TransientType"
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    static let all: Set<String> = [concealed, transient, autoGenerated]
}

@MainActor
final class SystemPasteboard: Pasteboard {
    private let pasteboard = NSPasteboard.general

    var changeCount: Int { pasteboard.changeCount }
    var types: [String] { pasteboard.types?.map(\.rawValue) ?? [] }

    func string() -> String? { pasteboard.string(forType: .string) }

    func write(_ text: String, concealed: Bool) -> Int {
        let marker = NSPasteboard.PasteboardType(PasteboardMarker.concealed)
        pasteboard.declareTypes(concealed ? [.string, marker] : [.string], owner: nil)
        pasteboard.setString(text, forType: .string)
        if concealed {
            pasteboard.setData(Data(), forType: marker)
        }
        return pasteboard.changeCount
    }
}

/// A pasteboard that lives in memory: demo mode's, and the tests'.
@MainActor
final class MemoryPasteboard: Pasteboard {
    private(set) var changeCount = 0
    private(set) var types: [String] = []
    private var text: String?

    func string() -> String? { text }

    func write(_ text: String, concealed: Bool) -> Int {
        copy(text, types: concealed ? ["public.utf8-plain-text", PasteboardMarker.concealed] : ["public.utf8-plain-text"])
        return changeCount
    }

    /// Plays another app copying something.
    func copy(_ text: String?, types: [String] = ["public.utf8-plain-text"]) {
        self.text = text
        self.types = types
        changeCount += 1
    }
}

/// Keeps the Mac's clipboard and the phone's in step.
///
/// macOS has no change notification for the pasteboard, so it is polled; the
/// timer runs only while sync is on and a phone is connected.
@MainActor
final class ClipboardSync {
    /// Larger text is not sent; the phone's clipboard is not meant for it.
    static let maxBytes = 1_000_000
    static let pollInterval: TimeInterval = 0.5

    private let pasteboard: any Pasteboard
    private let send: @MainActor (String) -> Void
    private var timer: Timer?
    /// The change count already looked at.
    private var seenCount: Int
    /// The change count our own last write produced.
    private var ownWriteCount: Int?
    /// Text that came from the phone. Not sent back even if another app
    /// copies it again (some clipboard tools re-copy what they see), until
    /// something else has been sent.
    private var receivedText: String?

    var isPolling: Bool { timer != nil }

    init(pasteboard: any Pasteboard, send: @escaping @MainActor (String) -> Void) {
        self.pasteboard = pasteboard
        self.send = send
        seenCount = pasteboard.changeCount
    }

    /// Starts or stops watching for copies. Whatever is on the pasteboard
    /// when watching starts is not sent: only copies made from then on.
    func setPolling(_ on: Bool) {
        guard on != isPolling else { return }
        if on {
            seenCount = pasteboard.changeCount
            let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.poll() }
            }
            // Lets the system batch the wakeups with others.
            timer.tolerance = Self.pollInterval / 2
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else {
            timer?.invalidate()
            timer = nil
        }
    }

    /// Looks at the pasteboard once, and sends a new copy if there is one.
    func poll() {
        let count = pasteboard.changeCount
        guard count != seenCount else { return }
        seenCount = count
        guard count != ownWriteCount else { return }
        guard let text = Self.sendable(types: pasteboard.types, read: pasteboard.string) else { return }
        guard text != receivedText else { return }
        receivedText = nil
        send(text)
    }

    /// Text from the phone, put on the Mac's pasteboard.
    func receive(_ text: String) {
        receivedText = text
        recordOwnWrite(pasteboard.write(text, concealed: false))
    }

    /// A one-time code, marked so clipboard managers skip it. The marker also
    /// keeps it from being sent back to the phone.
    func writeCode(_ code: String) {
        recordOwnWrite(pasteboard.write(code, concealed: true))
    }

    private func recordOwnWrite(_ count: Int) {
        ownWriteCount = count
        seenCount = count
    }

    /// The text to send, or `nil` if these contents must stay on the Mac.
    /// Takes the reader rather than the text so marked contents, such as a
    /// password, are never read at all.
    static func sendable(types: [String], read: () -> String?) -> String? {
        guard PasteboardMarker.all.isDisjoint(with: types) else { return nil }
        guard let text = read(), !text.isEmpty, text.utf8.count <= maxBytes else { return nil }
        guard !text.allSatisfy(\.isWhitespace) else { return nil }
        return text
    }
}
