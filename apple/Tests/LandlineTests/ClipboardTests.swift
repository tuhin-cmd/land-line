import LandlineKit
import Testing

@testable import Landline

@MainActor @Suite struct ClipboardSyncTests {
    let pasteboard = MemoryPasteboard()
    let sent = Box()

    final class Box { var values: [String] = [] }

    func sync() -> ClipboardSync {
        let sent = sent
        let sync = ClipboardSync(pasteboard: pasteboard) { sent.values.append($0) }
        sync.setPolling(true)
        return sync
    }

    @Test func sendsALaterCopy() {
        let sync = sync()
        pasteboard.copy("hello")
        sync.poll()
        sync.poll()
        #expect(sent.values == ["hello"])
        sync.setPolling(false)
    }

    @Test func doesNotSendWhatWasThereBefore() {
        pasteboard.copy("old")
        let sync = sync()
        sync.poll()
        #expect(sent.values.isEmpty)
        sync.setPolling(false)
    }

    @Test func copiesMadeWhileOffAreNotSentWhenTurnedOn() {
        let sync = sync()
        sync.setPolling(false)
        pasteboard.copy("while off")
        sync.setPolling(true)
        sync.poll()
        #expect(sent.values.isEmpty)
        sync.setPolling(false)
    }

    @Test func textFromThePhoneIsNotSentBack() {
        let sync = sync()
        sync.receive("from phone")
        #expect(pasteboard.string() == "from phone")
        #expect(!pasteboard.types.contains(PasteboardMarker.concealed))
        sync.poll()
        // A clipboard tool copying it again changes the count but not the text.
        pasteboard.copy("from phone")
        sync.poll()
        #expect(sent.values.isEmpty)

        pasteboard.copy("mine")
        sync.poll()
        pasteboard.copy("from phone")
        sync.poll()
        #expect(sent.values == ["mine", "from phone"])
        sync.setPolling(false)
    }

    @Test func codesAreNotSent() {
        let sync = sync()
        sync.writeCode("123456")
        sync.poll()
        #expect(pasteboard.types.contains(PasteboardMarker.concealed))
        #expect(sent.values.isEmpty)
        sync.setPolling(false)
    }

    @Test(arguments: [PasteboardMarker.concealed, PasteboardMarker.transient, PasteboardMarker.autoGenerated])
    func markedContentsAreNeverRead(marker: String) {
        var read = false
        let text = ClipboardSync.sendable(types: ["public.utf8-plain-text", marker]) {
            read = true
            return "secret"
        }
        #expect(text == nil)
        #expect(!read)
    }

    @Test func emptyBlankAndHugeTextStay() {
        #expect(ClipboardSync.sendable(types: []) { nil } == nil)
        #expect(ClipboardSync.sendable(types: []) { "" } == nil)
        #expect(ClipboardSync.sendable(types: []) { " \n\t" } == nil)
        let huge = String(repeating: "a", count: ClipboardSync.maxBytes + 1)
        #expect(ClipboardSync.sendable(types: []) { huge } == nil)
        let limit = String(repeating: "a", count: ClipboardSync.maxBytes)
        #expect(ClipboardSync.sendable(types: []) { limit } == limit)
        #expect(ClipboardSync.sendable(types: []) { "ok" } == "ok")
    }

    @Test func pollingRunsOnlyWhenAsked() {
        let sync = ClipboardSync(pasteboard: pasteboard) { _ in }
        #expect(!sync.isPolling)
        sync.setPolling(true)
        #expect(sync.isPolling)
        sync.setPolling(false)
        #expect(!sync.isPolling)
    }
}

@MainActor @Suite struct ClipboardModelTests {
    let backend = FakeBackend()
    let services = TestServices()

    func model() -> AppModel {
        let backend = backend
        let model = AppModel(services: services.services) { backend }
        model.start()
        return model
    }

    @Test func watchesOnlyWhileAPhoneIsConnectedAndSyncIsOn() {
        let model = model()
        #expect(!model.isWatchingClipboard)
        model.handle(.devicesChanged([device("Pixel", id: "p", .paired)]))
        #expect(model.isWatchingClipboard)
        model.setSyncClipboard(false)
        #expect(!model.isWatchingClipboard)
        model.setSyncClipboard(true)
        #expect(model.isWatchingClipboard)
        model.handle(.devicesChanged([device("Pixel", id: "p", reachable: false, .paired)]))
        #expect(!model.isWatchingClipboard)
        // An unpaired phone on the network does not count.
        model.handle(.devicesChanged([device("Other", id: "o", .notPaired)]))
        #expect(!model.isWatchingClipboard)
        model.stop()
    }

    @Test func macCopiesGoToTheCore() {
        let model = model()
        model.handle(.devicesChanged([device("Pixel", id: "p", .paired)]))
        services.pasteboard.copy("copied on the Mac")
        model.pollClipboard()
        #expect(backend.clipboardSent == ["copied on the Mac"])
        model.stop()
    }

    @Test func phoneClipboardReachesThePasteboardAndStaysThere() {
        let model = model()
        model.handle(.devicesChanged([device("Pixel", id: "p", .paired)]))
        model.handle(.clipboardReceived(deviceId: "p", text: "from the phone"))
        #expect(services.pasteboard.string() == "from the phone")
        #expect(model.recentClipboard == ["p"])
        model.pollClipboard()
        #expect(backend.clipboardSent.isEmpty)
        model.stop()
    }

    @Test func syncOffIgnoresThePhone() {
        services.settings.syncClipboard = false
        let model = model()
        model.handle(.devicesChanged([device("Pixel", id: "p", .paired)]))
        model.handle(.clipboardReceived(deviceId: "p", text: "from the phone"))
        #expect(services.pasteboard.string() == nil)
        model.stop()
    }
}

@MainActor @Suite struct ModelSettingsTests {
    let backend = FakeBackend()
    let services = TestServices()

    func model() -> AppModel {
        let backend = backend
        let model = AppModel(services: services.services) { backend }
        model.start()
        return model
    }

    @Test func downloadFolderGoesToTheCoreAndIsKept() {
        let model = model()
        model.setDownloadDir("/Users/test/Phone")
        #expect(backend.downloadDirs == ["/Users/test/Phone"])
        #expect(services.settings.downloadDir == "/Users/test/Phone")
        model.setDownloadDir(nil)
        #expect(backend.downloadDirs.last == AppModel.defaultDownloadDir)
        #expect(services.settings.downloadDir == nil)
    }

    @Test func launchAtLoginReflectsTheSystem() {
        let model = model()
        #expect(model.loginItemState == .disabled)
        model.setLaunchAtLogin(true)
        #expect(model.loginItemState == .enabled)
        #expect(model.loginItemError == nil)
    }

    @Test func launchAtLoginFailureIsExplained() {
        struct Refused: Error {}
        services.loginItem.failure = Refused()
        let model = model()
        model.setLaunchAtLogin(true)
        #expect(model.loginItemState == .disabled)
        #expect(model.loginItemError?.contains("development build") == true)
    }

    @Test func statesThatNeedTheUserSaySo() {
        #expect(LoginItemState.needsApproval.explanation?.contains("Login Items") == true)
        #expect(LoginItemState.unavailable.explanation != nil)
        #expect(LoginItemState.enabled.explanation == nil)
    }

    @Test func sharedItemsAndTransfersAreKeptForLater() {
        let model = model()
        model.handle(.textShared(deviceId: "p", text: "hi"))
        model.handle(.urlShared(deviceId: "p", url: "https://example.com"))
        let transfer = Transfer(
            id: 1, deviceId: "p", fileName: "a.jpg", direction: .incoming, bytesDone: 10, bytesTotal: 100,
            state: .inProgress)
        model.handle(.transferUpdated(transfer))
        #expect(model.sharedItems.map(\.kind) == [.text, .url])
        #expect(model.transfers[1] == transfer)
    }
}
